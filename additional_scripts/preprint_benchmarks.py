def make_two_channel_scene(
    seed: int,
    *,
    size_t: int = 4,
    size_z: int = 3,
    size_y: int = 96,
    size_x: int = 96,
    alpha: float = TRUE_ALPHA,
    noise_sigma: float = TWO_CHANNEL_NOISE_SIGMA,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Generate one synthetic ``TZYX`` two-channel scene with mild biological overlap.

    Returns
    -------
    tuple
        ``(true_source, true_target, measured_source, measured_target, true_alphas)``
        where the final element is a per-time-point vector, constant here.
    """

    rng = np.random.default_rng(int(seed))
    y_grid = np.arange(size_y, dtype=np.float32)[:, None]
    x_grid = np.arange(size_x, dtype=np.float32)[None, :]

    true_source = np.zeros((size_t, size_z, size_y, size_x), dtype=np.float32)
    true_target = np.zeros_like(true_source)

    for t in range(size_t):
        for z in range(size_z):
            for _ in range(2):
                true_source[t, z] += _gaussian_2d(
                    y_grid,
                    x_grid,
                    center_y=rng.uniform(20.0, 45.0) + 2.0 * np.sin((t + z) / 3.0),
                    center_x=rng.uniform(18.0, 45.0) + 2.0 * np.cos((t - z) / 2.0),
                    sigma_y=rng.uniform(4.0, 8.0),
                    sigma_x=rng.uniform(4.0, 8.0),
                    amplitude=rng.uniform(60.0, 110.0))
            for _ in range(2):
                true_target[t, z] += _gaussian_2d(
                    y_grid,
                    x_grid,
                    center_y=rng.uniform(55.0, 78.0) + 2.0 * np.cos((t + z) / 2.0),
                    center_x=rng.uniform(55.0, 78.0) + 2.0 * np.sin((t - z) / 3.0),
                    sigma_y=rng.uniform(5.0, 9.0),
                    sigma_x=rng.uniform(5.0, 9.0),
                    amplitude=rng.uniform(50.0, 95.0))

            # Add a small overlapping component so the benchmark is realistic.
            true_target[t, z] += 0.18 * _gaussian_2d(
                y_grid,
                x_grid,
                center_y=rng.uniform(40.0, 60.0),
                center_x=rng.uniform(40.0, 60.0),
                sigma_y=6.0,
                sigma_x=6.0,
                amplitude=rng.uniform(40.0, 80.0))

    measured_source = np.clip(
        true_source + rng.normal(0.0, noise_sigma, size=true_source.shape),
        0.0, None,).astype(np.float32)
    measured_target = np.clip(
        true_target + float(alpha) * true_source + rng.normal(0.0, noise_sigma, size=true_target.shape),
        0.0, None).astype(np.float32)
    true_alphas = np.full((size_t,), float(alpha), dtype=np.float32)
    return true_source, true_target, measured_source, measured_target, true_alphas


def make_time_varying_two_channel_scene(
    seed: int,
    *,
    size_t: int = 6,
    size_z: int = 3,
    size_y: int = 96,
    size_x: int = 96,
    alpha_start: float = TIME_VARYING_ALPHA_START,
    alpha_end: float = TIME_VARYING_ALPHA_END,
    noise_sigma: float = TWO_CHANNEL_NOISE_SIGMA,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Generate one synthetic ``TZYX`` two-channel scene with time-varying bleed-through.

    Returns
    -------
    tuple
        ``(true_source, true_target, measured_source, measured_target, true_alphas)``
        with one ground-truth alpha value per time point.
    """

    rng = np.random.default_rng(int(seed))
    y_grid = np.arange(size_y, dtype=np.float32)[:, None]
    x_grid = np.arange(size_x, dtype=np.float32)[None, :]

    true_source = np.zeros((size_t, size_z, size_y, size_x), dtype=np.float32)
    true_target = np.zeros_like(true_source)
    true_alphas = np.linspace(alpha_start, alpha_end, size_t, dtype=np.float32)

    for t in range(size_t):
        for z in range(size_z):
            for _ in range(2):
                true_source[t, z] += _gaussian_2d(
                    y_grid,
                    x_grid,
                    center_y=rng.uniform(18.0, 42.0) + 2.0 * np.sin((t + z) / 3.0),
                    center_x=rng.uniform(18.0, 42.0) + 2.0 * np.cos((t - z) / 3.0),
                    sigma_y=rng.uniform(4.0, 8.0),
                    sigma_x=rng.uniform(4.0, 8.0),
                    amplitude=rng.uniform(60.0, 110.0))
            for _ in range(2):
                true_target[t, z] += _gaussian_2d(
                    y_grid,
                    x_grid,
                    center_y=rng.uniform(54.0, 78.0) + 2.0 * np.cos((t + z) / 2.0),
                    center_x=rng.uniform(54.0, 78.0) + 2.0 * np.sin((t - z) / 2.0),
                    sigma_y=rng.uniform(5.0, 9.0),
                    sigma_x=rng.uniform(5.0, 9.0),
                    amplitude=rng.uniform(50.0, 95.0))

            true_target[t, z] += 0.25 * _gaussian_2d(
                y_grid,
                x_grid,
                center_y=rng.uniform(40.0, 60.0),
                center_x=rng.uniform(40.0, 60.0),
                sigma_y=6.0,
                sigma_x=6.0,
                amplitude=rng.uniform(40.0, 80.0))

    measured_source = np.clip(
        true_source + rng.normal(0.0, noise_sigma, size=true_source.shape),
        0.0, None).astype(np.float32)

    measured_target = np.zeros_like(true_target, dtype=np.float32)
    for t, alpha_value in enumerate(true_alphas):
        measured_target[t] = np.clip(
            true_target[t]
            + float(alpha_value) * true_source[t]
            + rng.normal(0.0, noise_sigma, size=true_target[t].shape),
            0.0, None)

    return true_source, true_target, measured_source, measured_target.astype(np.float32), true_alphas


def make_bidirectional_two_channel_scene(
    seed: int,
    *,
    size_t: int = 4,
    size_z: int = 3,
    size_y: int = 96,
    size_x: int = 96,
    alpha_01: float = TRUE_BIDIRECTIONAL_ALPHA_01,
    alpha_10: float = TRUE_BIDIRECTIONAL_ALPHA_10,
    noise_sigma: float = TWO_CHANNEL_NOISE_SIGMA,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Generate one synthetic bidirectionally mixed two-channel ``TZYX`` scene.

    Returns
    -------
    tuple
        ``(true_channel_0, true_channel_1, measured_channel_0, measured_channel_1)``
        with reciprocal bleed-through between both measured channels.
    """

    rng = np.random.default_rng(int(seed) + 7000)
    y_grid = np.arange(size_y, dtype=np.float32)[:, None]
    x_grid = np.arange(size_x, dtype=np.float32)[None, :]

    true_channel_0 = np.zeros((size_t, size_z, size_y, size_x), dtype=np.float32)
    true_channel_1 = np.zeros_like(true_channel_0)

    for t in range(size_t):
        for z in range(size_z):
            for _ in range(3):
                true_channel_0[t, z] += _gaussian_2d(
                    y_grid,
                    x_grid,
                    center_y=rng.uniform(18.0, 78.0) + 3.0 * np.sin((t + z) / 2.0),
                    center_x=rng.uniform(16.0, 78.0) + 3.0 * np.cos((t - z) / 2.0),
                    sigma_y=rng.uniform(4.0, 9.0),
                    sigma_x=rng.uniform(4.0, 9.0),
                    amplitude=rng.uniform(45.0, 105.0))
            for _ in range(3):
                true_channel_1[t, z] += _gaussian_2d(
                    y_grid,
                    x_grid,
                    center_y=rng.uniform(18.0, 78.0) + 3.0 * np.cos((t + z) / 3.0),
                    center_x=rng.uniform(18.0, 80.0) + 3.0 * np.sin((t - z) / 3.0),
                    sigma_y=rng.uniform(4.0, 9.0),
                    sigma_x=rng.uniform(4.0, 9.0),
                    amplitude=rng.uniform(45.0, 105.0))

            # Add one shared structural component so that the benchmark is not
            # artificially easy and still contains genuine spatial overlap.
            overlap_blob = _gaussian_2d(
                y_grid,
                x_grid,
                center_y=rng.uniform(34.0, 62.0),
                center_x=rng.uniform(34.0, 62.0),
                sigma_y=6.0,
                sigma_x=6.0,
                amplitude=rng.uniform(22.0, 48.0))
            true_channel_0[t, z] += 0.18 * overlap_blob
            true_channel_1[t, z] += 0.20 * overlap_blob

    measured_channel_0 = np.clip(
        true_channel_0
        + float(alpha_10) * true_channel_1
        + rng.normal(0.0, noise_sigma, size=true_channel_0.shape),
        0.0,
        None,
    ).astype(np.float32)
    measured_channel_1 = np.clip(
        true_channel_1
        + float(alpha_01) * true_channel_0
        + rng.normal(0.0, noise_sigma, size=true_channel_1.shape),
        0.0, None).astype(np.float32)

    return true_channel_0, true_channel_1, measured_channel_0, measured_channel_1


def make_multichannel_scene(
    seed: int,
    *,
    n_channels: int,
    size_y: int = 96,
    size_x: int = 96,
) -> np.ndarray:
    """
    Generate a sparse synthetic multi-channel fluorescence scene.

    The returned array has shape ``(C, Z, Y, X)`` with ``Z=1``.
    """

    rng = np.random.default_rng(int(seed))
    y_grid = np.arange(size_y, dtype=np.float32)[:, None]
    x_grid = np.arange(size_x, dtype=np.float32)[None, :]

    fluorophores = np.zeros((n_channels, 1, size_y, size_x), dtype=np.float32)
    for channel in range(n_channels):
        for _ in range(3):
            fluorophores[channel, 0] += _gaussian_2d(
                y_grid,
                x_grid,
                center_y=rng.uniform(12.0, size_y - 12.0),
                center_x=rng.uniform(12.0, size_x - 12.0),
                sigma_y=rng.uniform(3.0, 7.0),
                sigma_x=rng.uniform(3.0, 7.0),
                amplitude=rng.uniform(20.0, 60.0))
    return fluorophores
