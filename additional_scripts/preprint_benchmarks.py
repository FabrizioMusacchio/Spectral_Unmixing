def _gaussian_2d(
    y_grid: np.ndarray,
    x_grid: np.ndarray,
    *,
    center_y: float,
    center_x: float,
    sigma_y: float,
    sigma_x: float,
    amplitude: float,
) -> np.ndarray:
    """Return one anisotropic 2D Gaussian blob."""

    squared_distance = (
        ((y_grid - center_y) / sigma_y) ** 2
        + ((x_grid - center_x) / sigma_x) ** 2)
    return amplitude * np.exp(-0.5 * squared_distance)


def _normalize_for_display(
    image: np.ndarray,
    *,
    low: float = 0.5,
    high: float = 99.8,
    gamma: float = 0.8,
) -> np.ndarray:
    """Normalize one image to the interval ``[0, 1]`` for figure display."""

    image = np.asarray(image, dtype=np.float32)
    low_value = float(np.percentile(image, low))
    high_value = float(np.percentile(image, high))
    return _normalize_with_bounds(image, low_value=low_value, high_value=high_value, gamma=gamma)


def _normalize_with_bounds(
    image: np.ndarray,
    *,
    low_value: float,
    high_value: float,
    gamma: float = 0.8,
) -> np.ndarray:
    """Normalize one image to ``[0, 1]`` with explicit display bounds."""

    image = np.asarray(image, dtype=np.float32)
    if high_value <= low_value:
        return np.zeros_like(image, dtype=np.float32)
    normalized = np.clip((image - low_value) / (high_value - low_value), 0.0, 1.0)
    if gamma != 1.0:
        normalized = normalized ** float(gamma)
    return normalized


def _compute_display_bounds(
    image: np.ndarray,
    *,
    low: float = 0.5,
    high: float = 99.8,
) -> tuple[float, float]:
    """Return percentile-based lower and upper display bounds."""

    image = np.asarray(image, dtype=np.float32)
    return float(np.percentile(image, low)), float(np.percentile(image, high))


def _colorize_channel(
    image: np.ndarray,
    color: tuple[float, float, float],
    *,
    low_value: float | None = None,
    high_value: float | None = None,
    low: float = 0.5,
    high: float = 99.8,
    gamma: float = 0.8,
) -> np.ndarray:
    """Render one scalar image as a tinted RGB panel."""

    if low_value is None or high_value is None:
        low_value, high_value = _compute_display_bounds(image, low=low, high=high)
    normalized = _normalize_with_bounds(
        image,
        low_value=float(low_value),
        high_value=float(high_value),
        gamma=gamma)
    rgb = np.zeros(normalized.shape + (3,), dtype=np.float32)
    rgb[..., 0] = normalized * float(color[0])
    rgb[..., 1] = normalized * float(color[1])
    rgb[..., 2] = normalized * float(color[2])
    return np.clip(rgb, 0.0, 1.0)


def _multichannel_composite(channels: np.ndarray, *, gamma: float = 0.8) -> np.ndarray:
    """Create one RGB composite from a set of 2D channels."""

    composite = np.zeros(np.asarray(channels[0]).shape + (3,), dtype=np.float32)
    for channel_index, image in enumerate(np.asarray(channels, dtype=np.float32)):
        composite += _colorize_channel(image, DISPLAY_COLORS[channel_index % len(DISPLAY_COLORS)], 
                                       gamma=gamma)
    return np.clip(composite, 0.0, 1.0)


def _cyan_magenta_composite(channel_0: np.ndarray, channel_1: np.ndarray) -> np.ndarray:
    """Create a cyan-magenta RGB composite from two scalar images."""

    channel_0_n = _normalize_for_display(channel_0)
    channel_1_n = _normalize_for_display(channel_1)

    rgb = np.zeros(channel_0_n.shape + (3,), dtype=np.float32)
    rgb[..., 0] = channel_1_n
    rgb[..., 1] = channel_0_n
    rgb[..., 2] = np.maximum(channel_0_n, channel_1_n)
    return np.clip(rgb, 0.0, 1.0)


