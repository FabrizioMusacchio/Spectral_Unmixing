# %% BIDIRECTIONAL TWO-CHANNEL BENCHMARK LOGIC
def _apply_bidirectional_inverse_model(
    measured_channel_0: np.ndarray,
    measured_channel_1: np.ndarray,
    *,
    alpha_01: float,
    alpha_10: float,
) -> tuple[np.ndarray, np.ndarray]:
    """Solve the bidirectional 2x2 linear inverse model with clipping."""

    determinant = 1.0 - float(alpha_01) * float(alpha_10)
    if determinant <= 0.0:
        raise ValueError("The bidirectional benchmark requires a positive determinant. "
                        f"Got determinant={determinant!r}.")

    corrected_channel_0 = (measured_channel_0 - float(alpha_10) * measured_channel_1 ) / determinant
    corrected_channel_1 = (measured_channel_1 - float(alpha_01) * measured_channel_0 ) / determinant
    return (np.maximum(corrected_channel_0, 0.0).astype(np.float32),
            np.maximum(corrected_channel_1, 0.0).astype(np.float32))

def _bidirectional_metrics(
    *,
    corrected_channel_0: np.ndarray,
    corrected_channel_1: np.ndarray,
    measured_channel_0: np.ndarray,
    measured_channel_1: np.ndarray,
    true_channel_0: np.ndarray,
    true_channel_1: np.ndarray,
    estimated_alpha_01: float | None,
    estimated_alpha_10: float | None,
) -> dict[str, float | None]:
    """Compute benchmark metrics for one bidirectionally unmixed scene."""

    channel_0_nrmse = float(np.sqrt(np.mean((corrected_channel_0 - true_channel_0) ** 2)) / np.max(true_channel_0))
    channel_1_nrmse = float(np.sqrt(np.mean((corrected_channel_1 - true_channel_1) ** 2)) / np.max(true_channel_1))
    mixed_correlation = float(np.corrcoef(measured_channel_0.ravel(), measured_channel_1.ravel())[0, 1])
    corrected_correlation = float(np.corrcoef(corrected_channel_0.ravel(), corrected_channel_1.ravel())[0, 1])
    mixed_mutual_information = float(
        mutual_information_1d(
            measured_channel_0.ravel(),
            measured_channel_1.ravel(),
            bins=32))
    corrected_mutual_information = float(
        mutual_information_1d(
            corrected_channel_0.ravel(),
            corrected_channel_1.ravel(),
            bins=32))

    mean_alpha_abs_error = None
    alpha_01_abs_error = None
    alpha_10_abs_error = None
    if estimated_alpha_01 is not None and estimated_alpha_10 is not None:
        alpha_01_abs_error = abs(float(estimated_alpha_01) - TRUE_BIDIRECTIONAL_ALPHA_01)
        alpha_10_abs_error = abs(float(estimated_alpha_10) - TRUE_BIDIRECTIONAL_ALPHA_10)
        mean_alpha_abs_error = 0.5 * (alpha_01_abs_error + alpha_10_abs_error)

    return {"channel_0_nrmse": channel_0_nrmse,
            "channel_1_nrmse": channel_1_nrmse,
            "mixed_correlation": mixed_correlation,
            "corrected_correlation": corrected_correlation,
            "mixed_mutual_information": mixed_mutual_information,
            "corrected_mutual_information": corrected_mutual_information,
            "alpha_01_abs_error": alpha_01_abs_error,
            "alpha_10_abs_error": alpha_10_abs_error,
            "mean_alpha_abs_error": mean_alpha_abs_error}

